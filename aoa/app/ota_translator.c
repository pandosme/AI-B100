static const char* OTA_JS_COMMON =
"var OTA_VERSION = 1;\n"
"var OTA_MAX_BODY = 47;\n"
"var OTA_COMMANDS = {\n"
"  get: 0x01,\n"
"  set: 0x02,\n"
"  caps: 0x03,\n"
"  list: 0x04,\n"
"  get_response: 0x81,\n"
"  set_ack: 0x82,\n"
"  caps_response: 0x83,\n"
"  list_response: 0x84,\n"
"  error: 0xE0\n"
"};\n"
"var OTA_USE_CASES = { counting: 1, occupancy: 2, presence: 3, presenceAlert: 3 };\n"
"var OTA_CLASSES = ['human', 'car', 'bike', 'bus', 'truck', 'other'];\n"
"\n"
"function byte(value) {\n"
"  return Number(value) & 0xFF;\n"
"}\n"
"\n"
"function commandCode(value) {\n"
"  if (typeof value === 'number') return byte(value);\n"
"  var command = OTA_COMMANDS[String(value || '').replace(/-/g, '_')];\n"
"  if (command == null) throw new Error('Unsupported command ' + value);\n"
"  return command;\n"
"}\n"
"\n"
"function crc8(values) {\n"
"  var crc = 0;\n"
"  for (var index = 0; index < values.length; index++) {\n"
"    crc ^= byte(values[index]);\n"
"    for (var bit = 0; bit < 8; bit++) {\n"
"      crc = (crc & 0x80) ? ((crc << 1) ^ 0x07) & 0xFF : (crc << 1) & 0xFF;\n"
"    }\n"
"  }\n"
"  return crc;\n"
"}\n"
"\n"
"function bytesToHex(values) {\n"
"  return values.map(function (value) {\n"
"    return ('0' + byte(value).toString(16)).slice(-2);\n"
"  }).join('').toUpperCase();\n"
"}\n"
"\n"
"function hexToBytes(value) {\n"
"  if (Array.isArray(value)) return value.map(byte);\n"
"  var text = String(value || '').replace(/\\s+/g, '');\n"
"  if (!text.length || text.length % 2 || !/^[0-9a-f]+$/i.test(text)) {\n"
"    throw new Error('Payload must be even-length HEX');\n"
"  }\n"
"  var result = [];\n"
"  for (var index = 0; index < text.length; index += 2) {\n"
"    result.push(parseInt(text.slice(index, index + 2), 16));\n"
"  }\n"
"  return result;\n"
"}\n"
"\n"
"function appendU16(output, value) {\n"
"  var number = Number(value) & 0xFFFF;\n"
"  output.push(number & 0xFF, (number >> 8) & 0xFF);\n"
"}\n"
"\n"
"function readU16(values, offset) {\n"
"  return byte(values[offset]) | (byte(values[offset + 1]) << 8);\n"
"}\n"
"\n"
"function readU32(values, offset) {\n"
"  return (\n"
"    byte(values[offset]) +\n"
"    byte(values[offset + 1]) * 0x100 +\n"
"    byte(values[offset + 2]) * 0x10000 +\n"
"    byte(values[offset + 3]) * 0x1000000\n"
"  );\n"
"}\n"
"\n"
"function makeFrame(command, transactionId, body) {\n"
"  var frame = [byte(command), OTA_VERSION, byte(transactionId)].concat(body || []);\n"
"  if (frame.length + 1 > 51) throw new Error('OTA frame exceeds 51 bytes');\n"
"  frame.push(crc8(frame));\n"
"  return bytesToHex(frame);\n"
"}\n"
"\n"
"function classMask(value) {\n"
"  if (typeof value === 'number') return value & 0x3F;\n"
"  var mask = 0;\n"
"  if (Array.isArray(value)) {\n"
"    value.forEach(function (name) {\n"
"      var index = OTA_CLASSES.indexOf(name);\n"
"      if (index >= 0) mask |= 1 << index;\n"
"    });\n"
"    return mask;\n"
"  }\n"
"  value = value || {};\n"
"  OTA_CLASSES.forEach(function (name, index) {\n"
"    if (value[name]) mask |= 1 << index;\n"
"  });\n"
"  return mask;\n"
"}\n"
"\n"
"function classObject(mask) {\n"
"  var result = {};\n"
"  OTA_CLASSES.forEach(function (name, index) {\n"
"    result[name] = Boolean(mask & (1 << index));\n"
"  });\n"
"  return result;\n"
"}\n"
"\n"
"function useCaseIndex(value) {\n"
"  if (typeof value === 'number') return value;\n"
"  var index = OTA_USE_CASES[value];\n"
"  if (!index) throw new Error('Unknown use case ' + value);\n"
"  return index;\n"
"}\n"
"\n"
"function sceneFor(port, selector) {\n"
"  var group = OTA_SCENE_MAPS[String(port)];\n"
"  if (!group) throw new Error('No scene map for port ' + port);\n"
"  selector = selector || {};\n"
"  var scene;\n"
"  if (selector.index != null) {\n"
"    scene = group.scenes.filter(function (item) {\n"
"      return item.index === Number(selector.index);\n"
"    })[0];\n"
"  } else if (selector.id != null) {\n"
"    scene = group.scenes.filter(function (item) {\n"
"      return item.id === Number(selector.id);\n"
"    })[0];\n"
"  } else if (selector.name != null) {\n"
"    scene = group.scenes.filter(function (item) {\n"
"      return item.name === selector.name;\n"
"    })[0];\n"
"  }\n"
"  if (!scene) throw new Error('Scene not found');\n"
"  return { group: group, scene: scene };\n"
"}\n"
"\n"
"function sceneSelector(message) {\n"
"  if (message.sceneIndex != null) return { index: message.sceneIndex };\n"
"  if (message.sceneId != null) return { id: message.sceneId };\n"
"  return { name: message.scene != null ? message.scene : message.name };\n"
"}\n"
"\n"
"function integerCoordinate(value) {\n"
"  var number = Number(value);\n"
"  if (!Number.isInteger(number) || number < 0 || number > 1000) {\n"
"    throw new Error('Coordinates must be integers from 0 through 1000');\n"
"  }\n"
"  return number;\n"
"}\n"
"\n"
"function appendIntegerPoint(output, x, y) {\n"
"  var packed = integerCoordinate(x) + integerCoordinate(y) * 0x400;\n"
"  output.push(packed & 0xFF, (packed >> 8) & 0xFF, (packed >> 16) & 0x0F);\n"
"}\n";

