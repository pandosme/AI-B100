"    var identity = fields[0].split('/');\n"
"    result.hardware = identity[0];\n"
"    result.hardwareVersion = identity.slice(1).join('/');\n"
"    result.firmware = fields[1];\n"
"    result.powerSource = fields[2];\n"
"    result.temperatureC = Number(fields[3].replace(/C$/, ''));\n"
"    result.restartCounter = Number(fields[4].replace(/^R/, ''));\n"
"    result.devAddr = fields[5];\n"
"  }\n"
"  return result;\n"
"}\n"
"\n"
"function parseStructuredInformation(result, body) {\n"
"  var fixedLength = result.infoType === 'cameraInfo' ? 10 : 11;\n"
"  if (body.length < fixedLength) throw new Error('Structured information body too short');\n"
"  var fieldLengths = body.slice(2, result.infoType === 'cameraInfo' ? 6 : 7);\n"
"  var expectedLength = fixedLength + fieldLengths.reduce(function (sum, length) {\n"
"    return sum + length;\n"
"  }, 0);\n"
"  if (body.length !== expectedLength) throw new Error('Invalid structured information length');\n"
"  var offset = fixedLength;\n"
"  function readString(length) {\n"
"    var value = String.fromCharCode.apply(null, body.slice(offset, offset + length));\n"
"    offset += length;\n"
"    return value;\n"
"  }\n"
"\n"
"  if (result.infoType === 'cameraInfo') {\n"
"    result.model = readString(fieldLengths[0]);\n"
"    result.serial = readString(fieldLengths[1]);\n"
"    result.firmware = readString(fieldLengths[2]);\n"
"    result.appVersion = readString(fieldLengths[3]);\n"
"    result.uptimeHours = readU32(body, 6);\n"
"  } else if (result.infoType === 'bridgeInfo') {\n"
"    result.hardware = readString(fieldLengths[0]);\n"
"    result.hardwareVersion = readString(fieldLengths[1]);\n"
"    result.firmware = readString(fieldLengths[2]);\n"
"    result.powerSource = readString(fieldLengths[3]);\n"
"    result.devAddr = readString(fieldLengths[4]);\n"
"    var temperatureTenths = readU16(body, 7);\n"
"    if (temperatureTenths & 0x8000) temperatureTenths -= 0x10000;\n"
"    result.temperatureC = temperatureTenths / 10;\n"
"    result.restartCounter = readU16(body, 9);\n"
"  }\n"
"  return result;\n"
"}\n"
"\n"
"function parseFrame(port, input) {\n"
"  var frame = hexToBytes(input);\n"
"  if (frame.length < 4 || frame.length > 51) throw new Error('Invalid OTA frame length');\n"
"  if (crc8(frame.slice(0, -1)) !== frame[frame.length - 1]) throw new Error('CRC mismatch');\n"
"  if (frame[1] !== OTA_VERSION) throw new Error('Unsupported protocol version');\n"
"\n"
"  var command = frame[0];\n"
"  var body = frame.slice(3, -1);\n"
"  var result = {\n"
"    port: Number(port),\n"
"    command: commandName(command),\n"
"    commandCode: command,\n"
"    transactionId: frame[2]\n"
"  };\n"
"  var useCaseNames = { 1: 'counting', 2: 'occupancy', 3: 'presence' };\n"
"  var isScenePort = port === 131 || port === 132 || port === 133;\n"
"\n"
"  if (command === OTA_COMMANDS.error) {\n"
"    if (body.length !== 2) throw new Error('Invalid error response length');\n"
"    result.requestCommand = body[0];\n"
"    result.requestCommandName = commandName(body[0]);\n"
"    result.status = body[1];\n"
"    result.statusName = statusName(body[1]);\n"
"    return result;\n"
"  }\n"
"  if (command === OTA_COMMANDS.set_ack) {\n"
"    var statusOffset = port === 110 ? 0 : 1;\n"
"    if (body.length !== statusOffset + 1) throw new Error('Invalid SET acknowledgement length');\n"
"    result.status = body[statusOffset];\n"
"    result.statusName = statusName(result.status);\n"
"    if (port === 100) result.action = ({ 1: 'restartBridge', 2: 'resetAllData' })[body[0]] || body[0];\n"
"    else if (port === 130) result.useCase = useCaseNames[body[0]] || body[0];\n"
"    else if (isScenePort) result.sceneIndex = body[0];\n"
"    return result;\n"
"  }\n"
"  if (command === OTA_COMMANDS.caps_response) {\n"
"    return parseCapabilities(result, port, body);\n"
"  }\n"
"  if (isScenePort && command === OTA_COMMANDS.list) {\n"
"    result.page = body[0] || 0;\n"
"    return result;\n"
"  }\n"
"  if (isScenePort && command === OTA_COMMANDS.list_response) {\n"
"    if (body.length < 6) throw new Error('Scene list body too short');\n"
"    var entryCount = body[5];\n"
"    if (body.length !== 6 + entryCount * 6) throw new Error('Invalid scene list body length');\n"
"    var sceneGroup = OTA_SCENE_MAPS[String(port)];\n"
"    result.mapFingerprint = readU16(body, 0);\n"
"    result.totalScenes = body[2];\n"
"    result.page = body[3];\n"
"    result.pageCount = body[4];\n"
"    result.scenes = [];\n"
"    for (var sceneOffset = 0; sceneOffset < entryCount; sceneOffset++) {\n"
"      var entryOffset = 6 + sceneOffset * 6;\n"
"      var sceneIndex = body[entryOffset];\n"
"      var mappedScene = sceneGroup && sceneGroup.scenes.filter(function (item) {\n"
"        return item.index === sceneIndex;\n"
"      })[0];\n"
"      var scene = {\n"
"        index: sceneIndex,\n"
"        id: readU16(body, entryOffset + 1),\n"
"        fingerprint: readU16(body, entryOffset + 3),\n"
"        pointCount: body[entryOffset + 5]\n"
"      };\n"
"      if (mappedScene) scene.name = mappedScene.name;\n"
"      result.scenes.push(scene);\n"
"    }\n"
"    return result;\n"
"  }\n"
"  if (isScenePort && command === OTA_COMMANDS.get) {\n"
"    var requested = sceneFor(port, { index: body[0] });\n"
"    result.scene = {\n"
"      index: requested.scene.index,\n"
"      id: requested.scene.id,\n"
"      name: requested.scene.name,\n"
"      fingerprint: requested.scene.fingerprint,\n"
"      mapFingerprint: requested.group.mapFingerprint\n"
"    };\n"
"    result.page = body[1] || 0;\n"
"    return result;\n"
"  }\n"
"\n"
"  if (isScenePort && (command === OTA_COMMANDS.set || command === OTA_COMMANDS.get_response)) {\n"
"    if (body.length < 16) throw new Error('Scene body too short');\n"
"    var configVersion = body[0];\n"
"    if (configVersion !== 1 && configVersion !== 2) throw new Error('Unsupported scene config version');\n"
"    var sceneFieldLength = port === 133 ? 4 : 3;\n"
"    var coordinateBytes = configVersion === 2 ? 3 : 4;\n"
"    var pointCount = body[11];\n"
"    if (body.length !== 13 + sceneFieldLength + pointCount * coordinateBytes) {\n"
"      throw new Error('Invalid scene body length');\n"
"    }\n"
"\n"
"    var found = sceneFor(port, { index: body[1] });\n"
"    var config = { points: [] };\n"
"    if (port === 131) {\n"
"      config.direction = body[13] ? 'rightToLeft' : 'leftToRight';\n"
"      config.publishClasses = classObject(body[14]);\n"
"    } else if (port === 132) {\n"
"      config.publishClasses = classObject(body[13]);\n"
"      config.valueType = ['max', 'min', 'average'][body[14]] || 'unknown';\n"
"    } else {\n"
"      config.classes = classObject(body[13]);\n"
"      config.thresholdObjectCount = body[14];\n"
"      config.triggerDelaySeconds = readU16(body, 15);\n"
"    }\n"
"\n"
"    for (var index = 0; index < pointCount; index++) {\n"
"      var offset = 13 + sceneFieldLength + index * coordinateBytes;\n"
"      var x;\n"
"      var y;\n"
"      if (configVersion === 2) {\n"
"        if (body[offset + 2] & 0xF0) throw new Error('Invalid packed coordinate');\n"
"        var packed = body[offset] + body[offset + 1] * 0x100 + body[offset + 2] * 0x10000;\n"
"        x = packed & 0x3FF;\n"
"        y = (packed >> 10) & 0x3FF;\n"
"        if (x > 1000 || y > 1000) throw new Error('Coordinate outside 0 through 1000');\n"
"      } else {\n"
"        x = readU16(body, offset);\n"
"        y = readU16(body, offset + 2);\n"
"        if (x === 0x8000 || y === 0x8000) throw new Error('Invalid Q15 coordinate');\n"
"        if (x & 0x8000) x -= 0x10000;\n"
"        if (y & 0x8000) y -= 0x10000;\n"
"        x = Math.round((x / 32767 + 1) * 500);\n"
"        y = Math.round((y / 32767 + 1) * 500);\n"
"      }\n"
"      config.points.push({ x: x, y: y });\n"
"    }\n"
"\n"
"    result.scene = {\n"
"      index: body[1],\n"
"      id: readU16(body, 2),\n"
"      name: found.scene.name,\n"
"      fingerprint: readU16(body, 4),\n"
"      mapFingerprint: readU16(body, 6)\n"
"    };\n"
"    result.page = body[8];\n"
"    result.pageCount = body[9];\n"
"    result.pointStart = body[10];\n"
"    result.totalPointCount = body[12];\n"
"    result.coordinateSystem = { origin: 'topLeft', minimum: 0, maximum: 1000 };\n"
"    result.config = config;\n"
"    return result;\n"
"  }\n"
"\n"
"  if (port === 130 && command === OTA_COMMANDS.get) {\n"
"    result.useCase = useCaseNames[body[0]] || body[0];\n"
"    return result;\n"
"  }\n"
"  if (port === 130 && (command === OTA_COMMANDS.set || command === OTA_COMMANDS.get_response)) {\n"
"    result.config = { useCase: useCaseNames[body[0]] || body[0], enabled: Boolean(body[1]) };\n"
"    if (body[0] !== OTA_USE_CASES.presence) result.config.intervalMinutes = body[2];\n"
"    return result;\n"
"  }\n"
"  if (port === 110 && command === OTA_COMMANDS.get) return result;\n"
"  if (port === 110 && (command === OTA_COMMANDS.set || command === OTA_COMMANDS.get_response)) {\n"
"    result.config = { fieldMask: body[0], dataRate: body[1], adrEnabled: Boolean(body[2]) };\n"
"    return result;\n"
"  }\n"
"  if (port === 100 && command === OTA_COMMANDS.set) {\n"
"    result.action = ({ 1: 'restartBridge', 2: 'resetAllData' })[body[0]] || body[0];\n"
"    return result;\n"
"  }\n"
"  if (port === 120 && command === OTA_COMMANDS.get) {\n"
"    result.infoType = ({ 1: 'cameraInfo', 2: 'bridgeInfo' })[body[0]] || body[0];\n"
"    result.page = body[1] || 0;\n"
"    return result;\n"
"  }\n"
"  if (port === 120 && command === OTA_COMMANDS.get_response) {\n"
"    result.infoType = ({ 1: 'cameraInfo', 2: 'bridgeInfo' })[body[0]] || body[0];\n"
"    if (body[1] === 0x81) return parseStructuredInformation(result, body);\n"
"    result.page = body[1];\n"
"    result.pageCount = body[2];\n"
"    result.text = String.fromCharCode.apply(null, body.slice(4, 4 + body[3]));\n"
"    return parseInformation(result, result.pageCount === 1);\n"
"  }\n"
"\n"
"  result.body = body;\n"
"  return result;\n"
"}\n"
"\n"
"/**\n"
" * Decode one frame with Decode(port, hex), or one/more frames with\n"
" * Decode({ port: Number, messages: String[] }). Multi-page information and\n"
" * scene responses are validated and merged.\n"
" */\n"
"function Decode(input, payload) {\n"
"  var port;\n"
"  var frames;\n"
"  if (payload != null) {\n"
"    port = Number(input);\n"
"    frames = [payload];\n"
"  } else if (input && input.port != null) {\n"
"    port = Number(input.port);\n"
"    frames = input.messages || input.frames || [input.message || input.payload || input.hex];\n"
"  } else {\n"
"    throw new Error('Decode expects {port,message}, {port,messages}, or (port,HEX)');\n"
"  }\n"
"\n"
"  var decoded = frames.map(function (frame) {\n"
"    return parseFrame(port, frame);\n"
"  });\n"
"  if (decoded.length > 1 && port === 120 && decoded.every(function (item) {\n"
"    return item.commandCode === OTA_COMMANDS.get_response;\n"
"  })) {\n"
"    decoded.sort(function (left, right) { return left.page - right.page; });\n"
"    var information = decoded[0];\n"
"    if (decoded.length !== information.pageCount) throw new Error('Incomplete information pages');\n"
"    var text = '';\n"
"    decoded.forEach(function (item, index) {\n"
"      if (\n"
"        item.transactionId !== information.transactionId ||\n"
"        item.commandCode !== information.commandCode ||\n"
"        item.infoType !== information.infoType ||\n"
"        item.page !== index ||\n"
"        item.pageCount !== information.pageCount\n"
"      ) {\n"
"        throw new Error('Mismatched information pages');\n"
"      }\n"
"      text += item.text;\n"
"    });\n"
"    information.text = text;\n"
"    delete information.page;\n"
"    delete information.pageCount;\n"
"    delete information.appVersionFragment;\n"
"    return parseInformation(information, true);\n"
"  }\n"
"  var isScenePort = port >= 131 && port <= 133;\n"
"  if (decoded.length > 1 && isScenePort && decoded.every(function (item) { return item.config; })) {\n"
"    decoded.sort(function (left, right) { return left.page - right.page; });\n"
"    var first = decoded[0];\n"
"    var points = [];\n"
"    if (decoded.length !== first.pageCount) throw new Error('Incomplete scene pages');\n"
"\n"
"    decoded.forEach(function (item, index) {\n"
"      var itemFields = JSON.stringify(Object.assign({}, item.config, { points: [] }));\n"
"      var firstFields = JSON.stringify(Object.assign({}, first.config, { points: [] }));\n"
"      if (\n"
"        item.transactionId !== first.transactionId ||\n"
"        item.commandCode !== first.commandCode ||\n"
"        item.scene.id !== first.scene.id ||\n"
"        item.scene.fingerprint !== first.scene.fingerprint ||\n"
"        item.scene.mapFingerprint !== first.scene.mapFingerprint ||\n"
"        item.page !== index ||\n"
"        item.pageCount !== first.pageCount ||\n"
"        item.pointStart !== points.length ||\n"
"        itemFields !== firstFields\n"
"      ) {\n"
"        throw new Error('Mismatched scene pages');\n"
"      }\n"
"      points = points.concat(item.config.points);\n"
"    });\n"
"\n"
"    if (points.length !== first.totalPointCount) throw new Error('Incomplete scene points');\n"
"    first.config.points = points;\n"
"    delete first.page;\n"
"    delete first.pageCount;\n"
"    delete first.pointStart;\n"
"    return first;\n"
"  }\n"
"  return decoded.length === 1 ? decoded[0] : decoded;\n"
"}\n"
"\n"
"\n";

static void Respond_Translator(ACAP_HTTP_Response response, int encoder) {
	cJSON* maps = OTA_Scene_Maps_JSON(ACAP_Get_Config("settings"));
	char* maps_text = maps ? cJSON_Print(maps) : NULL;
	cJSON_Delete(maps);
	if (!maps_text) {
		ACAP_HTTP_Respond_Error(response, 500, "Unable to read AOA scene map");
		return;
	}
	GString* javascript = g_string_sized_new(16384);
	g_string_append(javascript, "/** AI-B100 AOA OTA JavaScript ");
	g_string_append(javascript, encoder ? "Encoder" : "Decoder");
	g_string_append(javascript, " - generated for the current camera scene map. */\n");
	g_string_append_printf(javascript, "var OTA_SCENE_MAPS = %s;\n\n", maps_text);
	g_string_append(javascript, OTA_JS_COMMON);
	g_string_append(javascript, encoder ? OTA_ENCODER_JS : OTA_DECODER_JS);
	free(maps_text);
	char filename[96];
	snprintf(filename, sizeof(filename), "aib100-aoa-ota-%s-%s.js",
		encoder ? "encoder" : "decoder", ACAP_DEVICE_Date());
	ACAP_HTTP_Header_FILE(response, filename, "application/javascript", javascript->len);
	ACAP_HTTP_Respond_Data(response, javascript->len, javascript->str);
	g_string_free(javascript, TRUE);
}

void HTTP_Endpoint_OTA_Encoder(ACAP_HTTP_Response response, const ACAP_HTTP_Request request) {
	(void)request;
	Respond_Translator(response, 1);
}

void HTTP_Endpoint_OTA_Decoder(ACAP_HTTP_Response response, const ACAP_HTTP_Request request) {
	(void)request;
	Respond_Translator(response, 0);
}